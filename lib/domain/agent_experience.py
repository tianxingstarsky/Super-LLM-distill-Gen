def _scope(scope):
    if not isinstance(scope, str) or scope not in EXPERIENCE_SCOPES:
        raise ValueError("invalid_agent_experience_scope")
    return scope


def _version(version):
    if type(version) is not int or version not in _TEXT_VERSIONS:
        raise ValueError("invalid_agent_experience_version")
    return version


def experience_scope(prompt_id):
    """Map concrete processing prompts, not node names, to one matching role."""
    return _PROMPT_SCOPES.get(prompt_id) if isinstance(prompt_id, str) else None


def default_experience_text(scope, *, version=AGENT_EXPERIENCE_VERSION):
    """Return literal full default text. Braces and whitespace are not rendered."""
    return _TEXT_VERSIONS[_version(version)][_scope(scope)]


def validate_agent_experience(value=None, *, version=AGENT_EXPERIENCE_VERSION):
    """Resolve partial per-role overrides to independent, complete configs.

    Missing text restores the pinned default. Disabled scopes retain literal
    edits (including an empty edit) but their text must not enter model context.
    An enabled scope cannot be empty. These rules validate transport, not the
    semantic correctness of a user's custom procedural instructions.
    """
    version = _version(version)
    if value is None:
        value = {}
    if not isinstance(value, dict) or set(value) - set(EXPERIENCE_SCOPES):
        raise ValueError("invalid_agent_experience")
    result = {}
    for scope in EXPERIENCE_SCOPES:
        config = value.get(scope, {})
        if not isinstance(config, dict) or set(config) - {"enabled", "text"}:
            raise ValueError("invalid_agent_experience")
        enabled = config.get("enabled", True)
        text = config.get("text", default_experience_text(scope, version=version))
        if (type(enabled) is not bool or not isinstance(text, str) or "\x00" in text or "\ufffd" in text
                or (enabled and not text.strip())):
            raise ValueError("invalid_agent_experience")
        try:
            size = len(text.encode("utf-8"))
        except UnicodeError as error:
            raise ValueError("invalid_agent_experience") from error
        if size > MAX_EXPERIENCE_BYTES:
            raise ValueError("invalid_agent_experience")
        result[scope] = {"enabled": enabled, "text": text}
    return result


def _sha(value):
    return hashlib.sha256(canonical(value).encode("utf-8")).hexdigest()


def snapshot_agent_experience(value=None, *, version=AGENT_EXPERIENCE_VERSION):
    """Pin every full role, exact text hashes and one reproducible package SHA."""
    version = _version(version)
    configs = validate_agent_experience(value, version=version)
    body = {"version": version, "kind": EXPERIENCE_KIND, "scopes": {
        scope: {**config, "text_sha256": hashlib.sha256(config["text"].encode("utf-8")).hexdigest(),
                "origin": "builtin" if config["text"] == default_experience_text(scope, version=version) else "custom"}
        for scope, config in configs.items()}}
    return {**body, "sha256": _sha(body)}


def validate_agent_experience_snapshot(value):
    """Reject changed text, role labels, enabled flags or incomplete snapshots."""
    if not isinstance(value, dict) or set(value) != {"version", "kind", "scopes", "sha256"}:
        raise ValueError("invalid_agent_experience_snapshot")
    try:
        version = _version(value["version"])
        scopes = value["scopes"]
        if value["kind"] != EXPERIENCE_KIND or not isinstance(scopes, dict) or set(scopes) != set(EXPERIENCE_SCOPES):
            raise ValueError("invalid_fields")
        configs = {}
        for scope, config in scopes.items():
            if not isinstance(config, dict) or set(config) != {"enabled", "text", "text_sha256", "origin"}:
                raise ValueError("invalid_fields")
            configs[scope] = {key: config[key] for key in ("enabled", "text")}
        expected = snapshot_agent_experience(configs, version=version)
        if value != expected:
            raise ValueError("snapshot_changed")
    except (ValueError, TypeError, KeyError, UnicodeError) as error:
        raise ValueError("invalid_agent_experience_snapshot") from error
    return deepcopy(expected)


def experience_prompt_payload(scope, config=None, *, version=AGENT_EXPERIENCE_VERSION):
    """A literal {enabled, text} payload for a role-specific personal template.

    The library's experience:<role> scope remains the caller's responsibility.
    This helper grants no storage access and executes no text.
    """
    scope = _scope(scope)
    resolved = validate_agent_experience({scope: config} if config is not None else None, version=version)
    return dict(resolved[scope])
