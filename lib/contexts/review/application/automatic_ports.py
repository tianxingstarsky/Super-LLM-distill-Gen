"""Ports for scoring/correction and authenticated rework; records keep their wire fields."""
from __future__ import annotations
from typing import Protocol


class AutomaticReviewPort(Protocol):
    @property
    def run_id(self) -> str: ...
    @property
    def authenticated_revision(self) -> bool: ...
    def payload(self, target: str, record: dict) -> dict: ...
    def evidence(self, record: dict) -> dict | None: ...
    def repair(self, target, record, evidence, key, feedback, instruction) -> tuple[dict, str | None]: ...
    def score(self, target, record, evidence, key, instruction) -> dict: ...
    def regenerate_native(self, item: dict) -> list[dict]: ...
    def record_revision_style(self, target, original, updated) -> None: ...
    def independent_cot_assessment(self, record, *, human=False) -> dict: ...


class ReviewCollectionsPort(Protocol):
    @property
    def run_id(self) -> str: ...
    @property
    def finalizing(self) -> bool: ...
    def skip_review(self) -> None: ...
    def check_cancel(self) -> None: ...
    def payload(self, target, record) -> dict: ...
    def review_item(self, item) -> list[dict]: ...
    def review_items(self, items, action): ...
    def split_reviewed(self, rows, collections, *, targets) -> dict: ...
    def align_cot_sft(self, result, collections) -> None: ...


class RepairBranchPort(Protocol):
    @property
    def run_id(self) -> str: ...
    def authenticate(self, inputs: list[dict]) -> None: ...
    def prepare(self, inputs: list[dict]) -> None: ...
    def review(self, inputs: list[dict]): ...
    def publish(self, rows) -> dict: ...
    def complete(self, status: str) -> dict: ...
