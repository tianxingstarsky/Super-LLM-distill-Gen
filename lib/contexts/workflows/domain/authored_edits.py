"""Atomic literal edits to an authored candidate, never an approval decision."""
from copy import deepcopy
import json

from jsonschema import Draft202012Validator

from .authored_submission import strict_tool_schema
from .authored_trace_transport import authored_response_schema, prepare_authored_response
from .reasoning_checklist import checklist_digest

EDIT_AUTHORED = "edit_authored_candidate"


def edit_schema(*, answer_required):
    text = {"type": "string", "minLength": 1}
    fields = ["reasoning", "answer"] if answer_required else ["reasoning"]
    edit = {"type": "object", "additionalProperties": False,
            "required": ["field", "old_text", "new_text"], "properties": {
                "field": {"type": "string", "enum": fields},
                "old_text": text, "new_text": {"type": "string"}}}
    return {"type": "object", "additionalProperties": False,
            "required": ["base_sha256", "edits", "reasoning_trace"], "properties": {
                "base_sha256": text,
                "edits": {"type": "array", "items": edit, "maxItems": 32},
                "reasoning_trace": authored_response_schema(answer_required=answer_required)["properties"]["reasoning_trace"]}}


def authored_edit_tool(*, answer_required):
    return {"type": "function", "function": {"name": EDIT_AUTHORED, "strict": True,
        "description": "Only after a tool receipt explicitly requests editing an existing candidate: "
            "submit literal, uniquely matching replacements in reasoning/answer and the updated evidence trace. "
            "Preserve sound reasoning. The program applies all edits atomically. This is not quality approval. "
            "For initial generation use submit_authored_candidate instead.",
        "parameters": strict_tool_schema(edit_schema(answer_required=answer_required))}}


def apply_authored_edits(candidate, assistant, *, answer_required):
    calls = assistant.get("tool_calls", [])
    if (assistant.get("content", "").strip() or len(calls) != 1
            or calls[0].get("function", {}).get("name") != EDIT_AUTHORED):
        raise ValueError("authored_edit_missing_or_ambiguous")

    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError("authored_edit_duplicate_field")
            result[key] = value
        return result

    patch = json.loads(calls[0]["function"]["arguments"], object_pairs_hook=unique)
    if not Draft202012Validator(edit_schema(answer_required=answer_required)).is_valid(patch):
        raise ValueError("authored_edit_schema_invalid")
    if patch["base_sha256"] != checklist_digest(candidate):
        raise ValueError("authored_edit_stale_candidate")
    revised = deepcopy(candidate)
    for edit in patch["edits"]:
        field, old, new = edit["field"], edit["old_text"], edit["new_text"]
        if old == new or revised[field].count(old) != 1:
            raise ValueError("authored_edit_target_not_unique_or_unchanged")
        revised[field] = revised[field].replace(old, new, 1)
    revised["reasoning_trace"] = deepcopy(patch["reasoning_trace"])
    # Reuse the full existing schema and reasoning checks on the assembled body.
    # Unedited arguments remain byte-for-byte intact, not regenerated by an LLM.
    _, validation = prepare_authored_response(revised, answer_required=answer_required)
    if validation["errors"] or validation.get("content_issue"):
        raise ValueError("authored_edit_invalid_candidate:" + str(validation.get("content_issue") or validation["errors"]))
    if revised == candidate:
        raise ValueError("authored_edit_without_change")
    return revised, patch
