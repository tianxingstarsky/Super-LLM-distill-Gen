"""Production batches remain replayable streams; adapters own files and transactions."""
from __future__ import annotations
from contextlib import AbstractContextManager
from dataclasses import dataclass
from typing import Protocol
from .execution_ports import RecordBatch
from ..domain.production_rounds import ProductionProgress, ProductionRoundPlan


@dataclass
class PreparedProductionRound:
    generated: RecordBatch
    ready: RecordBatch
    sources: RecordBatch
    arithmetic_count: int
    generated_count: int
    arithmetic_stop: str | None


class ProductionPort(Protocol):
    def open_session(self) -> AbstractContextManager[ProductionProgress]: ...
    def check_cancel(self) -> None: ...
    def prepare_round(self, progress: ProductionProgress, plan: ProductionRoundPlan) -> PreparedProductionRound: ...
    def execute_and_commit(self, progress, plan, batch) -> dict: ...
    def refresh_progress(self, progress) -> None: ...
    def record_progress(self, progress, receipt) -> None: ...
    def begin_finalization(self, progress) -> None: ...
    def completion_status(self, progress, counts, stop) -> str: ...
    def publish_final(self, progress) -> dict: ...
    def reconcile_for_replenishment(self, progress) -> dict: ...
    def complete(self, progress) -> dict: ...
    def reset_replenishment(self) -> None: ...
    def needs_replenishment(self) -> bool: ...
