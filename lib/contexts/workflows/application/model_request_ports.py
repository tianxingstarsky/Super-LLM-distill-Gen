"""Checkpoint and invocation operations consumed by a workflow node call."""
from typing import Any, Callable, Protocol
from ..domain.model_request import NodeModelRequest


class NodeRequestPort(Protocol):
    @property
    def recipe(self) -> dict: ...
    @property
    def stage(self) -> str: ...
    def checkpoint(self, key: Any, action: Callable[[], Any]) -> Any: ...
    def invoke(self, request: NodeModelRequest) -> Any: ...
    def finish_stream(self, *, interrupted: bool) -> None: ...
    def captured_result(self, value: dict) -> Any: ...
