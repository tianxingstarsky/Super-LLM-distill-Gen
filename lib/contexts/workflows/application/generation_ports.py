"""Effects required by SFT/CoT authoring; providers and files remain outside."""
from __future__ import annotations
from collections.abc import Callable, MutableMapping, Sequence
from typing import Any, Protocol


class GenerationNodePort(Protocol):
    def request(self, key: list, role: str, prompt_id: str, payload: dict, **options) -> Any: ...
    def reject(self, record: dict, reason: str) -> dict: ...
    def assess(self, key: list, context: dict, candidate: Any, **options) -> dict: ...
    def check_style(self, key: list, style: dict, reasoning: str, answer: str) -> dict: ...
    def check_adherence(self, key: list, prompt_id: str, payload: dict, **options) -> dict: ...
    def check_contract(self, key: list, record: dict, messages: list, **options) -> dict: ...
    def generation_style(self, stage: str, sample_id: str) -> dict | None: ...
    def invalidate_checkpoint(self, key: list) -> None: ...


class SftGenerationPort(GenerationNodePort, Protocol):
    def source_evidence(self, source: dict) -> str: ...
    def generate_directed_sft(self, source: dict) -> list[dict]: ...


class DirectedSftPort(GenerationNodePort, Protocol):
    def separated_questions(self) -> bool: ...
    def source_evidence(self, source: dict) -> str: ...
    def selected_evidence_text(self, source: dict, contract: dict) -> str: ...
    def selected_evidence_blocks(self, source: dict, contract: dict) -> list[str]: ...
    def prepare_source_request(self, payload: dict, source: dict, contract: dict | None) -> dict: ...


class CotGenerationPort(GenerationNodePort, Protocol):
    @property
    def current_stage(self) -> str: ...

    def independent_cot_assessment(self, record: dict) -> dict: ...
    def prepare_source_request(self, payload: dict, source: dict, contract: dict | None) -> dict: ...
    def validate_native_prefill(self) -> None: ...
    def request_native_answer(self, key: list, payload: dict, *, catch_empty: bool, **options) -> Any: ...
    def checkpoint(self, key: list, action: Callable[[], Any]) -> Any: ...
    def checkpoint_has(self, key: list) -> bool: ...
    def event(self, kind: str, **fields) -> None: ...
    def extract_cot(self, record: dict) -> list[dict]: ...
    def generate_styled_cot(self, record: dict, style: dict) -> list[dict]: ...
    def generate_native_answer(self, record: dict, task: dict, style: dict, feedback: Any, attempt: int) -> tuple: ...


class ReasoningDeliveryPort(GenerationNodePort, Protocol):
    def prepare_source_request(self, payload: dict, source: dict, contract: dict | None) -> dict: ...
    def skip_trim_stage(self) -> None: ...
    def prepare_trim_stage(self) -> None: ...
    def trim_collections(self, collections: MutableMapping, targets: Sequence[str]) -> None: ...
    def apply_reasoning_trim(self, collections: MutableMapping, *, targets=None) -> None: ...
    def publish_finalized_sft(self, collections: MutableMapping) -> None: ...
