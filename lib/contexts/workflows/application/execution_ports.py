"""Ports owned by the execution use cases, independent of the legacy engine."""
from __future__ import annotations

from contextlib import AbstractContextManager
from dataclasses import dataclass
from typing import Any, Iterator, Protocol

from ..domain.execution import BatchGenerationPlan, BatchOutcome, ExecutionRoute


Record = dict[str, Any]


class RecordBatch(Protocol):
    """Replayable records, usually disk-backed; never require a list conversion."""

    def __len__(self) -> int: ...
    def __iter__(self) -> Iterator[Record]: ...


StageCollections = dict[str, RecordBatch]


@dataclass(frozen=True)
class PreparedBatch:
    source_records: RecordBatch
    generation_candidates: RecordBatch


class RunSessionPort(Protocol):
    """One exclusive run attempt, including durable error and cancellation handling."""

    def exclusive(self) -> AbstractContextManager: ...
    def reload_status(self) -> str: ...
    def verify_existing_delivery(self) -> None: ...
    def start_attempt(self, *, resume: bool) -> None: ...
    def verify_pinned_inputs(self) -> None: ...
    def route(self) -> ExecutionRoute: ...
    def run_repair(self) -> Record: ...
    def run_production(self) -> Record: ...
    def complete(self, outcome: BatchOutcome) -> None: ...
    def record_cancellation(self) -> None: ...
    def record_failure(self, error: Exception) -> None: ...
    def result(self) -> Record: ...


class BatchRuntimePort(Protocol):
    """Stage operations. Scheduling policy belongs to GenerateDatasetBatch."""

    def plan(self) -> BatchGenerationPlan: ...
    def prepare_inputs(self, plan: BatchGenerationPlan) -> PreparedBatch: ...
    def cpt_records(self, sources: RecordBatch) -> RecordBatch: ...
    def run_stage(self, stage: str, records: RecordBatch) -> RecordBatch: ...
    def skip_stage(self, stage: str) -> None: ...
    def directed_dialogues(self, candidates: RecordBatch, *, needs_sft: bool,
                           needs_multiturn: bool) -> StageCollections | None: ...
    def eligible_records(self, stage: str, records: RecordBatch) -> RecordBatch: ...
    def preference_exports(self, pairs: RecordBatch, targets: frozenset[str]) -> StageCollections: ...
    def arithmetic_records(self) -> RecordBatch: ...
    def finalize_reasoning(self, collections: StageCollections) -> None: ...
    def publish(self, collections: StageCollections) -> None: ...
    def outcome(self, collections: StageCollections) -> BatchOutcome: ...
