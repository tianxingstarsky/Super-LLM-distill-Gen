"""Ports used by one dialogue invocation. Records and keys retain their wire shape."""
from __future__ import annotations
from typing import Protocol
from ..domain.dialogue import DialogueSource


class DialoguePort(Protocol):
    def prompt_text(self, prompt_id: str) -> str: ...
    def prepare_source(self, unit: dict, style: dict | None) -> DialogueSource: ...
    def generation_style(self, stage: str, sample_id: str) -> dict | None: ...
    def reject(self, unit: dict, reason: str) -> dict: ...
    def request(self, key, role: str, prompt_id: str, data: dict, **options) -> dict: ...
    def assess(self, key, context: dict, message, prompt_id="workflow.jev_score", **options) -> dict: ...
    def next_dialogue_step(self, unit: dict, messages: list, state: dict, **options) -> dict: ...
    def check_contract(self, key, unit: dict, messages: list, **options) -> dict: ...
    def check_style(self, key, style: dict, reasoning: str, answer: str) -> dict: ...
    def separated_questions(self) -> bool: ...
    def learner_prompt(self, contract: dict) -> str: ...
