"""Request lifecycle ports; no SDK object is required by the use cases."""
from __future__ import annotations
from typing import Any, Callable, ContextManager, Protocol

StreamCallback = Callable[[dict], None]
CancelCheck = Callable[[], None]


class BudgetReservationPort(Protocol):
    def check(self) -> None: ...
    def reserve(self, amount: float) -> str: ...


class RequestAdmissionPort(Protocol):
    api_format: str
    cancel_check: CancelCheck | None

    def admit(self, check_cancel: CancelCheck, on_wait: StreamCallback | None) -> ContextManager: ...
    def budget_guards(self) -> list[BudgetReservationPort]: ...
    def settle_all(self, reservations: list, amount: float) -> None: ...
    def account_usage(self, prompt_tokens: int, completion_tokens: int,
                      reservations: list, reservation_usd: float) -> None: ...
    def commit_details(self, target: dict | None, details: dict) -> None: ...
    def classify_error(self, error: Exception) -> dict: ...
    def rejected_before_generation(self, error: Exception) -> bool: ...
    def retry_delay(self, error: Exception, attempt: int) -> float: ...
    def defer(self, delay: float) -> None: ...
    def wait_retry(self, delay: float, check_cancel: CancelCheck) -> None: ...


class ModelRequestPort(RequestAdmissionPort, Protocol):
    json_supported: bool | None

    def prepare_request(self, messages: list[dict], max_tokens: int | None,
                        *, reasoning_prefix: str | None, thinking: bool | None) -> tuple[int | None, float]: ...
    def request(self, messages: list[dict], **options) -> tuple[str, int, int]: ...
    def is_format_unsupported(self, error: Exception) -> bool: ...


class JSONResponsePort(Protocol):
    def chat(self, messages: list[dict], **options) -> str: ...
    def parse_json(self, output: str) -> Any: ...
    def commit_details(self, target: dict | None, details: dict) -> None: ...


class ToolRequestPort(RequestAdmissionPort, Protocol):
    def prepare_request(self, messages: list[dict], tools: list[dict], *,
                        max_tokens: int | None, temperature: float, retries: int,
                        tool_choice: str) -> float: ...
    def request(self) -> object: ...
    def response_usage(self, response: object) -> tuple[int, int]: ...
    def complete_response(self, response: object, *, tool_choice: str) -> dict: ...
    def response_details(self, response: object) -> dict: ...
