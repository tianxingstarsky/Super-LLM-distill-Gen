ADAPTIVE_USER_EXPRESSION = """按场景续写用户，而不是选择统一的用户文风
以下两种表达方式同等有效，可在同一段交流、同一条发言中自然结合：
一是简洁承接：只说当下想表达的一点，允许省略、短回应、局部补充、未完全想清楚的请求；所指从实际公开前文恢复，需要澄清时保留真实缺口。
二是情境叙事：从用户当前处境出发，把感受、动机、相关背景、犹豫或互相牵制的要求说得较完整；可以边说边形成想法，不必整理成规格、问题清单或一段故事旁白。
选择依据是本轮要做什么、刚收到什么回应、用户当时知道什么以及已有表达习惯。直接回应一个已明确的选择时可以简短；解释顾虑、补充相互关联的条件或想清楚方向时可以展开。这些是适用可能性，不是触发后必须执行的规则。同一用户可以先展开后收缩，也可以先简短后详细；情境没有变化时无需为了多样性强行切换。两种方式不是固定人物类型，不按年龄、职业、语言或身份刻板分配，不设字数、句数、轮次配额或固定开头，不要求每段都出现两种方式。
用户自身已经说过的话是其语言习惯和观点的依据；助手发言是用户正在回应的对象，不能因此把助手的术语、条目结构或确定口气当成用户必须模仿的声音。允许用户借用一个刚听到的词、赞同一部分、反对一部分、联想到新用途、提出新偏好或改变主意，不把这些正常变化一律视为偏离设定。不要为了显得聪明而把用户每次发言都整理成一份完整需求分析。
区分用户已经表达的条件、助手刚提出的建议与已核实事实。助手提出一个方案，不表示用户已经实施；助手声称一个结论，不表示它已经得到确认。用户可以对建议表态、追问、保留怀疑，也可暂时接受讨论方向，但内部状态不能把这种接受升级成外部事实验证。合成场景允许一致的当下目标、偏好和预期担忧，不能借叙事补写已做过的实验、工具执行、测量结果或与既定背景冲突的经历。隐藏教师知识、回答者思考、未来台词和指导员设定不能冒充用户已见内容。
节点中用户明确的 question_rules、实际语言要求与固定原话继续有效；本策略不覆盖它们，也不改变输出字段、知识可见性与自然结束条件。只交付当前阶段约定的发言或设计对象，不把表达方式名称、选择分析、场景旁白或本段规则写入用户发言。
"""


DIRECTOR_EXPRESSION_DISPATCH = """指导员的表达调度
初始任务设计可用现有 expression_design 的 form、verbosity、interaction_style 等开放文本记录本次表达建议，并用 dialogue_design 的现有字段交代相关处境与可调整方向；只写有用的建议，不要求填满，不新增策略标签或必填字段。情境是生成依据，不是需要逐句照演的剧本。
request_phase=next_turn 时，先前 expression_design 只是上一时刻的建议；依据实际最新交流重新判断，仅在有用时通过 dialogue_state.expression_design 更新本轮表达。连续性保留在用户的目标、知情范围和相容的语言习惯中，不冻结长度、句式或情绪。结束条件成立就结束，不能只为展示另一种表达继续对话。
closed_book 的独立发言路径继续将本轮可公开的表达建议放入既有 question_brief.expression_design，供发言者自行实现；简报不得夹带教师事实、参考答案或预写用户全文。有线索路径则由指导员将本轮选择落实到实际 question 或 user_message。两条路径都不把内部的场景说明和选择理由混进真实用户话语。
"""


